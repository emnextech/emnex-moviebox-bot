create table if not exists public.telegram_users (
    telegram_user_id bigint primary key,
    username text,
    first_name text,
    last_name text,
    plan text not null default 'basic' check (plan in ('basic', 'pro')),
    plan_expires_at timestamptz,
    created_at timestamptz not null default timezone('utc', now()),
    updated_at timestamptz not null default timezone('utc', now()),
    last_seen_at timestamptz not null default timezone('utc', now())
);

create index if not exists idx_telegram_users_plan_expires
    on public.telegram_users (plan, plan_expires_at);

create table if not exists public.telegram_events (
    id bigint generated by default as identity primary key,
    telegram_user_id bigint not null references public.telegram_users (telegram_user_id) on delete cascade,
    action text not null,
    outcome text not null,
    subject_id text,
    subject_type text,
    season integer,
    episode integer,
    quality text,
    plan_at_time text not null check (plan_at_time in ('basic', 'pro')),
    metadata jsonb not null default '{}'::jsonb,
    created_at timestamptz not null default timezone('utc', now())
);

create index if not exists idx_telegram_events_user_created
    on public.telegram_events (telegram_user_id, created_at desc);

create index if not exists idx_telegram_events_created
    on public.telegram_events (created_at desc);

create or replace function public.set_telegram_users_updated_at()
returns trigger
language plpgsql
as $$
begin
    new.updated_at = timezone('utc', now());
    return new;
end;
$$;

drop trigger if exists trg_telegram_users_updated_at on public.telegram_users;

create trigger trg_telegram_users_updated_at
before update on public.telegram_users
for each row
execute function public.set_telegram_users_updated_at();
